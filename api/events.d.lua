---@meta

---General registration names accepted by computer.on. start, timer,
---signal_changed and dashboard_click use their dedicated registration paths.
---@alias TC.GeneralEventName 'peripheral_attach'|'peripheral_detach'|'monitor_resize'|'monitor_touch'|'power_restored'|'modem_message'

---Host-owned event envelope copied for each delivery. Handlers run through the
---scheduler, never recursively from service/GUI calls. Earlier effects are not
---replayed on ordinary load. Queue overflow faults the affected saved run and
---clears its still-owned Logic outputs; it is not a successful empty event.
---@class TC.BaseEvent
---@field name string Event discriminator; each concrete event lists its name.
---@field tick TC.Tick Dispatch tick unless the event documents an activation tick.
---@field sequence integer Synchronized creation/admission order, not a native pointer.
---@field computer_id TC.ComputerId Recipient placed computer identity.
---@field run_id string Recipient active run generation.

---Queued once on explicit successful Run/Apply when start is exported. Not
---generated by validation, Save, ordinary cold load or electrical cycling.
---@class TC.StartEvent: TC.BaseEvent
---@field name 'start' Startup event discriminator.

---Named timer delivery. scheduled_tick is the first due deadline; tick is actual
---callback dispatch and may be later. Recurring timers coalesce overdue intervals
---into one event and advance to the first aligned deadline after admission.
---Equal deadlines retain timer creation order through reload. Cancellation removes
---pending deadlines and queued, undispatched timer events without replay.
---@class TC.TimerEvent: TC.BaseEvent
---@field name 'timer' Timer event discriminator.
---@field timer_id TC.TimerId Timer that owns this pending delivery.
---@field scheduled_tick TC.Tick Original first due deadline for this delivery.
---@field interval_ticks? integer Positive recurring interval; absent for one-shot.
---@field missed integer Nonnegative skipped recurring intervals beyond this event.
---@field payload? TC.Data Independent registration-time copy, absent if omitted/nil.

---Physical attachment transition, not an initial inventory when registering.
---Discover explicitly after registration if a current inventory is needed.
---Transitions are channel-qualified; detach precedes replacement attach for the
---same binding. Electricity loss alone does not detach a native carrier.
---@class TC.PeripheralAttach: TC.BaseEvent
---@field name 'peripheral_attach' Attachment discriminator.
---@field peripheral TC.PeripheralName Currently attached identity.
---@field peripheral_type string Public peripheral family name.
---@field wire TC.Wire Independently reachable channel.

---Physical detachment notification. Authority is revoked and still-owned outputs
---are cleaned before delivery, even without a registered guest handler.
---@class TC.PeripheralDetach: TC.BaseEvent
---@field name 'peripheral_detach' Detachment discriminator.
---@field peripheral TC.PeripheralName Detached identity; old handles do not retarget.
---@field peripheral_type string Prior public peripheral family name.
---@field wire TC.Wire Channel that lost authority.
---@field reason 'wire_removed'|'removed'|'regrouped'|'force_changed'|'surface_changed'|'limit'|'unavailable' Physical transition reason.

---Legacy accepted event only. power_restored remains a legal general registration
---name but no new events are produced. Custom computers need no electricity.
---Historical admitted records retain normal ordering and cancellation.
---@class TC.PowerRestored: TC.BaseEvent
---@field name 'power_restored' Inert legacy event discriminator.
---@field outage_start_tick TC.Tick Historical outage start, not a current power policy.
---@field restored_tick TC.Tick Historical restoration observation.

---A monitor event is delivered once per logical display per registration, even
---when both colors reach it. wires orders red before green, not alphabetically;
---wire is its first entry, not a bridge.
---@class TC.MonitorEvent: TC.BaseEvent
---@field peripheral TC.PeripheralName Logical monitor identity.
---@field wire TC.Wire First currently authorized discovery color.
---@field wires TC.Wire[] Authorized colors in red-before-green order; caller may choose another entry.

---Logical terminal geometry changed. Old wrappers/coordinates may no longer be
---valid; rediscover and inspect dimensions. Notifications may coalesce to the
---latest geometry while retaining the original prior dimensions.
---@class TC.MonitorResize: TC.MonitorEvent
---@field name 'monitor_resize' Resize event discriminator.
---@field old_width integer Previous terminal width in character columns.
---@field old_height integer Previous terminal height in character rows.
---@field width integer Current terminal width in character columns.
---@field height integer Current terminal height in character rows.
---@field reason 'tiles'|'scale' Cause of geometry/scale notification.

---A selected monitor character cell was activated through the supported player
---interaction. Coordinates are terminal cells, not world tiles or mosaic pixels.
---@class TC.MonitorTouch: TC.MonitorEvent
---@field name 'monitor_touch' Touch event discriminator.
---@field x integer One-based character column.
---@field y integer One-based character row.
---@field player_index integer Activating player index, not a player object.
---@field sample_tick TC.Tick Original synchronized monitor activation tick.

---Selected-color input connection state. Only the selected red or green field is
---present; the other is absent. Initial previous connectivity is false.
---@class TC.InputConnectivity
---@field red? boolean Present only for red selection; physical connection status.
---@field green? boolean Present only for green selection; physical connection status.

---One effective identity/count difference; disappearing signals use current=0.
---@class TC.SignalChange
---@field signal TC.SignalId Native identity with optional fields preserved.
---@field previous TC.Int32 Prior admitted count, zero when previously absent.
---@field current TC.Int32 Current observed count, zero when now absent.

---Named Logic subscription delivery. previous is the last successfully admitted
---sample or registration baseline, not the last callback that happened to run.
---Changes compare effective identities/counts and connectivity, not ordering or
---explicit defaults. Connectivity-only changes can have an empty changes array.
---Every watched physical input/color is read once per simulation tick, sharing
---the observation across isolated subscriptions; direct reads remain fresh.
---Native circuit observations reflect the engine's update state, not guaranteed
---same-tick feedback. sample_tick is observation time; tick is dispatch time.
---@class TC.SignalChanged: TC.BaseEvent
---@field name 'signal_changed' Logic event discriminator; not computer.on-registerable.
---@field subscription_id TC.SubscriptionId Run and exact binding registration.
---@field peripheral TC.PeripheralName Logic handler identity.
---@field wire TC.Wire Computer-to-handler discovery path, not the input selection.
---@field input TC.InputSelection Selected physical input color.
---@field sample_tick TC.Tick Tick of the native snapshot read.
---@field initial boolean True only for the requested initial notification.
---@field resync boolean Current-input resynchronization after physical unavailability or supported legacy upgrade, never replay or an electrical-cycle notification.
---@field previous TC.Signal[] Isolated prior sample; empty for initial notification.
---@field current TC.Signal[] Isolated current native sample; no sorting guarantee.
---@field changes TC.SignalChange[] Complete effective differences; no sorting guarantee.
---@field previous_connected TC.InputConnectivity Prior selected-color connectivity.
---@field connected TC.InputConnectivity Current selected-color connectivity.

---Left-button activation of an enabled native Dashboard button. tick is the
---activation tick, not necessarily dispatch. Each explicit subscription gets its
---own event; configuring/viewing a panel alone does not subscribe. Layout identity,
---enabled state, player access, subscription/run and selected path are rechecked
---before delivery. No guest callback runs within the GUI event handler.
---@class TC.DashboardClick: TC.BaseEvent
---@field name 'dashboard_click' Dashboard subscription event discriminator.
---@field peripheral TC.PeripheralName Exact Dashboard identity.
---@field wire TC.Wire This subscription's discovery color.
---@field subscription_id TC.SubscriptionId Recipient run-bound registration.
---@field tab integer Numbered occupied tab slot, 1..6.
---@field button string Stable button widget ID, not a native GUI element.
---@field player_index integer Activating player index.

---Accepted radar datagram delivered through a modem_message registration. Numeric
---channels are distinct from wire colors. A dual-color receiver gets one event
---per registration/receiver, with authorized wires ordered red before green. Data is isolated for
---each delivery. Radio does not expose remote peripherals or sender authority.
---No ACK, automatic reply, retry, retained mailbox or guaranteed reception exists.
---@class TC.ModemMessage: TC.BaseEvent
---@field name 'modem_message' Radio event discriminator.
---@field peripheral TC.PeripheralName Local receiving modem, not the sender.
---@field wire TC.Wire First authorized receiver discovery color.
---@field wires TC.Wire[] Receiver discovery colors in red-before-green order at acceptance.
---@field channel integer Received numeric channel, 0..65535.
---@field replyChannel integer Sender-specified numeric reply channel, 0..65535.
---@field message? TC.Data Copied message; absent for explicit top-level nil.
---@field distance? number Euclidean distance in tiles on one surface; absent across surfaces.
---@field sent_tick TC.Tick Simulation tick of transmission acceptance.

---Union of all supported scheduled guest event shapes, including the inert legacy
---power event. Register by handler name, not by persisting a function value.
---@alias TC.Event TC.StartEvent|TC.TimerEvent|TC.PeripheralAttach|TC.PeripheralDetach|TC.PowerRestored|TC.MonitorResize|TC.MonitorTouch|TC.SignalChanged|TC.DashboardClick|TC.ModemMessage
