#!/usr/bin/env python3
"""Extract the authoritative fenced planning programs into packaged parser fixtures."""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / 'openspec'
# Preserve complete saved-program sources and fixture names. Console inputs
# are not saved programs; archives are never live contract inputs.
SOURCES = ('api/examples.md',) + tuple(
    f'specs/{cap}/lua-api.md' for cap in (
        'computer-runtime', 'device-configurator', 'device-lifecycle',
        'kv-database', 'logic-handler', 'monitor-display',
        'peripheral-network', 'program-editor', 'production-statistics', 'dashboard-interface'))
DEST = ROOT / 'examples/planning-programs.lua'

def quote(s):
    pad = '='
    while ']' + pad + ']' in s:
        pad += '='
    return '[' + pad + '[' + s + ']' + pad + ']'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    records = []
    for relative in sorted(SOURCES):
        p = CONTRACT / relative
        for i, match in enumerate(re.finditer(r'```lua\n(.*?)\n```', p.read_text(), re.S), 1):
            source = match[1]
            records.append('  {name=' + quote(relative + ':' + str(i)) + ',sha256=' + quote(hashlib.sha256(source.encode()).hexdigest()) + ',source=' + quote(source) + '}')
    text = '-- Generated by tools/planning_examples.py; parse/compile evidence only.\nreturn {\n' + ',\n'.join(records) + '\n}\n'
    if args.check:
        if DEST.read_text() != text:
            raise SystemExit('stale planning programs: run tools/planning_examples.py')
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(text)
    print(f'planning_programs={len(records)}')

if __name__ == '__main__':
    main()
