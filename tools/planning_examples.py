#!/usr/bin/env python3
"""Preserve former planning-program identities from canonical runnable sources."""
import argparse
import hashlib
from pathlib import Path
from api_migration import examples, example_source

ROOT = Path(__file__).resolve().parents[1]

DEST = ROOT / 'examples/planning-programs.lua'

def quote(s):
    pad = '='
    while ']' + pad + ']' in s:
        pad += '='
    return '[' + pad + '[' + s + ']' + pad + ']'

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    records = []
    for record in examples():
        if record['kind'] != 'program':
            continue
        source = example_source(record)
        name = record['path'].removeprefix('openspec/') + ':' + str(record['index'])
        records.append('  {name=' + quote(name) + ',sha256=' + quote(hashlib.sha256(source.encode()).hexdigest()) + ',source=' + quote(source) + '}')
    text = '-- Generated by tools/planning_examples.py; parse/compile evidence only.\nreturn {\n' + ',\n'.join(records) + '\n}\n'
    if args.check:
        if DEST.read_text() != text:
            raise SystemExit('stale planning programs: run tools/planning_examples.py')
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(text)
    print(f'planning_programs={len(records)}')

if __name__ == '__main__':
    main()
