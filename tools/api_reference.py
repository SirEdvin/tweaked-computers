"""Website pages and native topics from the same validated LuaLS records."""
import hashlib
import json
from pathlib import Path
import posixpath
import re

from lua_api import FAMILIES, api_blocks, api_markdown, validate_api_records

ROOT = Path(__file__).resolve().parents[1]
NOTICE = '<!-- Generated by tools/player_docs.py from api/**/*.d.lua; do not edit. -->\n\n'
PAGES = {
    'computer': ('Computer', 'computer'), 'peripheral': ('Peripheral discovery', 'peripheral'),
    'monitor': ('Monitor', 'monitor'), 'dashboard': ('Dashboard', 'dashboard'),
    'kv_database': ('KV database', 'kv'), 'logic_handler': ('Logic handler', 'logic'),
    'configurator': ('Configurator', 'configurator'), 'recipe_searcher': ('Recipe Searcher', 'recipe-searcher'),
    'factoriopedia_interface': ('Factoriopedia Interface', 'factoriopedia-interface'),
    'production_statistics': ('Production Statistics', 'production-statistics'),
    'modem': ('Radar modem', 'modem'), 'speaker': ('Programmable speaker', 'speaker'),
}


def lua(value):
    if isinstance(value, str):
        eq = '='
        while ']' + eq + ']' in value:
            eq += '='
        return '[' + eq + '[\n' + value + ']' + eq + ']'
    if isinstance(value, list):
        return '{\n' + ',\n'.join(lua(v) for v in value) + '\n}'
    if isinstance(value, dict):
        return '{\n' + ',\n'.join('[ ' + lua(k) + ' ]=' + lua(v) for k, v in sorted(value.items())) + '\n}'
    raise ValueError('unsupported native documentation value: ' + type(value).__name__)


def references(record):
    found = set(record.get('references', []))
    for signature in record.get('signatures', []):
        for part in ('parameters', 'returns'):
            for value in signature[part]:
                found.update(references(value))
    for field in record.get('fields', {}).values():
        found.update(references(field))
    return found


def generate(records, root=ROOT):
    validate_api_records(records)
    groups, locations = [], {}

    def group(identity, title, category, page, names):
        blocks = [] if names == [title] else [{'kind': 'heading', 'text': title}]
        for name in names:
            if name in locations:
                raise ValueError('duplicate reference placement: ' + name)
            if not re.fullmatch(r'[A-Za-z_][A-Za-z_0-9.]*', name):
                raise ValueError('unsupported public reference identity: ' + name)
            blocks.extend(api_blocks(records[name]))
            locations[name] = {'page': 'docs/player/' + page, 'topic': identity}
        groups.append({'id': identity, 'title': title, 'category': category,
                       'blocks': blocks, 'text': '\n\n'.join(b['text'] for b in blocks),
                       'page': page, 'names': names})

    for family, identity in FAMILIES.items():
        title, page = PAGES[family]
        names = [identity]
        if family == 'dashboard':
            names += ['TC.DashboardBase', 'TC.ChartDashboard']
        if family in ('computer', 'peripheral'):
            names += [family]
        topic = 'computer' if family == 'computer' else 'peripheral.' + ('discovery' if family == 'peripheral' else family)
        group(topic, title + ' — ' + identity, 'Computer' if family == 'computer' else 'Peripherals',
              'api/' + page + '.md', names)
    for namespace in ('table', 'string', 'math'):
        identity = records[namespace]['type']
        group('language.' + namespace, namespace + ' — ' + identity, 'Language',
              'api/' + namespace + '.md', [identity, namespace])
    group('language.colors', 'Colors — TC.Color', 'Language', 'api/colors.md', ['TC.Color', 'colors', 'colours'])
    globals_ = sorted(name for name in records if not name.startswith('TC.') and name not in locations)
    group('language.globals', 'Guarded global helpers', 'Language', 'api/globals.md', globals_)
    for name in sorted(set(records) - set(locations)):
        group('type.' + name, name, 'Types', 'api/types/' + name + '.md', [name])

    routes = json.loads((root / 'tools/data/api-route-migration.json').read_text())
    products = {}

    def link(name, page):
        target = locations[name]['page'].removeprefix('docs/player/')
        relative = posixpath.relpath(target, posixpath.dirname(page))
        return '[' + name + '](' + relative + '#symbol-' + name + ')'

    def aliases(page, headings):
        # Keep old externally linked fragments, but do not duplicate new heading IDs.
        generated = {re.sub(r'[^\w\s-]', '', h).strip().lower().replace(' ', '-') for h in headings}
        return ''.join('<a id="' + a + '"></a>\n' for a in routes.get(page, []) if a not in generated) + '\n'

    for entry in groups:
        page = entry['page']
        body = NOTICE + aliases(page, [entry['title']] + [b['text'] for b in entry['blocks'] if b['kind'] == 'heading'])
        body += '# ' + entry['title'] + '\n\n'
        body += 'Source: public `api/` declarations. [All public types and globals](' + posixpath.relpath('api/types.md', posixpath.dirname(page)) + ').\n\n'
        for name in entry['names']:
            body += '<a id="symbol-' + name + '"></a>\n\n' + api_markdown(api_blocks(records[name])) + '\n'
        refs = sorted(set().union(*(references(records[n]) for n in entry['names'])))
        if refs:
            body += '## Referenced types\n\n' + '\n'.join('- ' + link(n, page) for n in refs) + '\n'
        products['docs/player/' + page] = body.rstrip() + '\n'

    indexes = {
        'api/common.md': ('Shared rules, errors and events', [n for n, r in records.items() if r['source']['file'] in ('common.d.lua', 'events.d.lua')]),
        'api/limits.md': ('Effective limits', [n for n, r in records.items() if r['source']['file'] == 'generated/limits.d.lua']),
        'api/settings.md': ('Configurator settings: write inputs and readback', [n for n in records if 'Lua' in n and n.endswith('ControlBehavior')]),
        'api/schemas.md': ('Configurator nested types and enums', [n for n in records if n.startswith('TC.Config.') and not n.endswith('ControlBehavior')]),
        'api/types.md': ('All public types and globals', sorted(records)),
    }
    for page, (title, names) in indexes.items():
        body = NOTICE + aliases(page, [title]) + '# ' + title + '\n\n'
        body += 'Each linked definition has complete fields, domains and behavior notes. In game, search its exact public name in Reference.\n\n'
        body += '\n'.join('- ' + link(n, page) for n in sorted(names)) + '\n'
        if page == 'api/limits.md':
            body += '\n[Adjusting shared work budgets](../budget-settings.md). Defaults are not current save values.\n'
        products['docs/player/' + page] = body

    topics = [{k: v for k, v in entry.items() if k not in ('page', 'names')} for entry in groups]
    products['scripts/ui/api-reference.lua'] = '-- Generated by tools/player_docs.py; inert data, never guest code.\nreturn ' + lua({'topics': topics, 'locations': locations}) + '\n'
    nav = ['  # BEGIN GENERATED API TYPES', '  - Native helpers:']
    for namespace in ('globals', 'table', 'string', 'math', 'colors'):
        nav.append('      - ' + namespace + ': api/' + namespace + '.md')
    nav += ['  - Public type index: api/types.md', '  - Named types:']
    for entry in groups:
        if entry['category'] == 'Types':
            nav += ['      - ' + entry['title'] + ': ' + entry['page']]
    nav += ['  # END GENERATED API TYPES']
    config = (root / 'mkdocs.yml').read_text()
    config = re.sub(r'^  # BEGIN GENERATED API TYPES\n.*?^  # END GENERATED API TYPES\n', '', config, flags=re.M | re.S)
    if config.count('\nvalidation:\n') != 1:
        raise ValueError('missing unique MkDocs validation boundary')
    products['mkdocs.yml'] = config.replace('\nvalidation:\n', '\n' + '\n'.join(nav) + '\nvalidation:\n')
    return products, topics, locations


def check_products(products, root=ROOT):
    for relative, body in products.items():
        path = root / relative
        if not path.is_file() or path.read_text() != body:
            raise ValueError('stale generated reference: ' + relative)


def inputs(root=ROOT):
    paths = set((root / 'api').rglob('*.d.lua'))
    paths.update((root / 'tools/data').glob('*.json'))
    paths.update((root / 'examples').rglob('*.lua'))
    paths.update((root / 'scripts/services').glob('*.lua'))
    paths.update(root / name for name in ('api/README.md', 'docs/api-coverage.json',
        'tests/api_inventory.lua', 'settings.lua', 'scripts/runtime/limits.lua',
        'scripts/runtime/budget-settings.lua', 'scripts/runtime/computer.lua',
        'scripts/runtime/environment.lua', 'scripts/monitor-model.lua', 'scripts/speaker-limits.lua'))
    paths.update(root / 'tools' / name for name in (
        'api_reference.py', 'api_migration.py', 'lua_api.py', 'player_docs.py', 'limit_docs.py',
        'configuration_catalog.py', 'configuration_docs.py', 'luals-export.lua', 'luals-lock.json', 'luals-docs.json'))
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(paths)}


def provenance(products, root=ROOT):
    return {'format_version': 1, 'tool': json.loads((root / 'tools/luals-lock.json').read_text()),
            'inputs': inputs(root), 'outputs': {p: hashlib.sha256(body.encode()).hexdigest() for p, body in sorted(products.items())}}


def check_freshness(root=ROOT):
    """Package gate; full parser/projection parity remains the --check gate."""
    path = root / 'docs/api-reference-provenance.json'
    if not path.is_file():
        raise ValueError('missing generated reference provenance; run tools/player_docs.py')
    receipt = json.loads(path.read_text())
    # The reviewed navigation inventories every API page, even a missing file.
    pages = set(re.findall(r': (api/[A-Za-z_0-9./-]+\.md)$', (root / 'mkdocs.yml').read_text(), re.M))
    expected = {'docs/player/' + page for page in pages if page != 'api/language.md'}
    expected.update(('mkdocs.yml', 'scripts/ui/api-reference.lua', 'docs/player/examples.md', 'docs/api-migration.md'))
    if receipt.get('format_version') != 1 or set(receipt.get('outputs', {})) != expected:
        raise ValueError('invalid generated reference output inventory; run tools/player_docs.py')
    if receipt['inputs'] != inputs(root):
        raise ValueError('stale generated reference inputs; run tools/player_docs.py')
    for relative, digest in receipt['outputs'].items():
        p = root / relative
        if not p.is_file() or hashlib.sha256(p.read_bytes()).hexdigest() != digest:
            raise ValueError('stale generated reference output: ' + relative)
    return receipt
